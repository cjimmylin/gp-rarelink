"""Majeed syndrome papers we could not get, for Jimmy to look for by hand (2026-11-15).

Reads data/literature/majeed/manifest.csv, oa_elsewhere.csv and
nopmid_candidates.csv and writes

  reports/majeed_papers_to_find_<date>.md   (tables, by priority)
  reports/majeed_papers_to_find_<date>.csv  (one row per paper, with a column to fill in)

Part 1 is every paper that passed title/abstract screening but has no open full
text (fulltext_screen = not_accessible). Priority:
  A  relevance yes, case report or case series/cohort (new patients likely)
  B  relevance yes, review; or relevance unclear, case report or case series/cohort
  C  relevance unclear, review (kept only if it has a per-patient table)
Part 2 is the records with no PMID whose title names Majeed syndrome or LPIN2;
they were never screened.

  uv run python analysis/corpus/majeed_papers_to_find.py
"""

from __future__ import annotations

import csv
from datetime import date
from pathlib import Path

BASE = Path("data/literature/majeed")
OUT = Path("reports")
PRIMARY = {"case report", "case series/cohort"}


def priority(r: dict) -> str:
    if r["relevance"] == "yes":
        return "A" if r["study_type"] in PRIMARY else "B"
    return "B" if r["study_type"] in PRIMARY else "C"


def reason(r: dict) -> str:
    n = r.get("notes", "")
    return n.split("screen: ", 1)[1].strip() if "screen: " in n else ""


def md_cell(s: str) -> str:
    return s.replace("|", "/").replace("\n", " ")


def main() -> int:
    today = date.today().isoformat()
    rows = list(csv.DictReader((BASE / "manifest.csv").open(newline="")))
    oa = {r["pmid"]: r for r in csv.DictReader((BASE / "oa_elsewhere.csv").open(newline=""))}
    todo = [r for r in rows if r.get("in_extraction_corpus") == "true" and r.get("fulltext_screen") == "not_accessible"]
    for r in todo:
        r["_prio"] = priority(r)
        o = oa.get(r["pmid"], {})
        r["_free"] = {"OA": "open copy listed", "F": "free copy listed"}.get(o.get("best", ""), "")
        if r["_free"] and o.get("free_sites"):
            r["_free"] += f" ({o['free_sites'].replace(';', ', ')})"
    todo.sort(key=lambda r: (r["_prio"], 0 if r["_free"] else 1, -int(r["year"] or 0)))
    nopmid = list(csv.DictReader((BASE / "nopmid_candidates.csv").open(newline="")))

    OUT.mkdir(exist_ok=True)
    cols = ["priority", "pmid", "doi", "year", "first_author", "journal", "title", "relevance", "study_type",
            "europe_pmc_free_listing", "why_it_may_matter", "pubmed_url", "doi_url", "found_by_hand", "file_name", "comment"]
    with (OUT / f"majeed_papers_to_find_{today}.csv").open("w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=cols)
        w.writeheader()
        for r in todo:
            w.writerow({"priority": r["_prio"], "pmid": r["pmid"], "doi": r["doi"], "year": r["year"],
                        "first_author": r["first_author"], "journal": r["journal"], "title": r["title"],
                        "relevance": r["relevance"], "study_type": r["study_type"], "europe_pmc_free_listing": r["_free"],
                        "why_it_may_matter": reason(r), "pubmed_url": f"https://pubmed.ncbi.nlm.nih.gov/{r['pmid']}/",
                        "doi_url": f"https://doi.org/{r['doi']}" if r["doi"] else "",
                        "found_by_hand": "", "file_name": "", "comment": ""})
        for r in nopmid:
            doi = r["doi"]
            w.writerow({"priority": "N", "pmid": "", "doi": doi, "year": r["year"], "first_author": "", "journal": r["venue"],
                        "title": r["title"], "relevance": "not screened", "study_type": r["type"],
                        "europe_pmc_free_listing": "", "why_it_may_matter": "no PMID; title names Majeed syndrome or LPIN2",
                        "pubmed_url": "", "doi_url": f"https://doi.org/{doi}" if doi else r["ids"].split("; ")[0],
                        "found_by_hand": "", "file_name": "", "comment": ""})

    counts = {p: sum(1 for r in todo if r["_prio"] == p) for p in "ABC"}
    labels = {"A": "Priority A: reports of Majeed patients (most important)",
              "B": "Priority B: reviews that likely describe patients, and possible primary reports",
              "C": "Priority C: reviews that name Majeed syndrome (useful only if they have a per-patient table)"}
    lines = [
        f"# Majeed syndrome papers to find by hand ({today})",
        "",
        "*Generated by `analysis/corpus/majeed_papers_to_find.py` from `data/literature/majeed/`. "
        "These papers passed title/abstract screening, but no open full text was found through Europe PMC, PMC or Unpaywall. "
        "The same list with columns to fill in is `reports/majeed_papers_to_find_" + today + ".csv`.*",
        "",
        f"**{len(todo)} PubMed papers** (A {counts['A']}, B {counts['B']}, C {counts['C']}) and **{len(nopmid)} records outside PubMed** (part 2). "
        "\"Free copy listed\" means Europe PMC lists a free or open copy outside PMC that the pipeline did not fetch; try those first.",
        "",
        "Save what you find as `<PMID>.pdf` (or a short title for part 2) and tell Claude where it is. PDFs anywhere under `data/literature/` are git-ignored, so they are not published with the repository. Under D-32 (open access only) and D-47 (free copies until 2026-11-30, for the six diseases), a subscription copy is a separate decision.",
        "",
    ]
    for p in "ABC":
        sel = [r for r in todo if r["_prio"] == p]
        if not sel:
            continue
        lines += [f"## {labels[p]} ({len(sel)})", "",
                  "| PMID | Year | First author | Title | Journal | Link | Free copy listed | Why it may matter |",
                  "|---|---|---|---|---|---|---|---|"]
        for r in sel:
            link = f"[doi](https://doi.org/{r['doi']})" if r["doi"] else ""
            lines.append(f"| [{r['pmid']}](https://pubmed.ncbi.nlm.nih.gov/{r['pmid']}/) | {r['year']} | {md_cell(r['first_author'])} | "
                         f"{md_cell(r['title'])} | {md_cell(r['journal'])} | {link} | {md_cell(r['_free']) or '—'} | {md_cell(reason(r))} |")
        lines.append("")
    lines += [f"## Part 2: records outside PubMed that name Majeed syndrome or LPIN2 ({len(nopmid)})", "",
              "Found by Europe PMC or OpenAlex with no PMID; not screened. Some are book-chapter fragments or translations of PubMed papers above.", "",
              "| Year | Title | Venue | Type | Link |", "|---|---|---|---|---|"]
    for r in nopmid:
        link = f"[doi](https://doi.org/{r['doi']})" if r["doi"] else f"[record]({r['ids'].split('; ')[0]})" if r["ids"].startswith("http") else r["ids"]
        lines.append(f"| {r['year']} | {md_cell(r['title'])} | {md_cell(r['venue'])} | {md_cell(r['type'])} | {link} |")
    (OUT / f"majeed_papers_to_find_{today}.md").write_text("\n".join(lines) + "\n")
    print(f"{len(todo)} PubMed papers (A {counts['A']}, B {counts['B']}, C {counts['C']}); {len(nopmid)} outside PubMed")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
