"""Summarize the browser run over free copies, and check each saved file is the right paper.

Reads data/literature/free_copies/results_<date>.jsonl (git-ignored) and the saved
files, and writes two committed files holding identifiers and outcomes only:

  analysis/corpus/free_copies/status_<date>.csv   one row per paper
  reports/free_copies_<date>.md                   summary + what is left to fetch by hand

Identity check: share of the paper's title words (from the manifest, 4+ letters)
found in the text of the saved file's first pages (pdftotext) or HTML. A file
under 0.6 is flagged `check_identity`; a one-page PDF is flagged `one_page`
(often a first-page preview of an older article).

  python3 analysis/corpus/free_copies/summarize.py --date 2026-11-14
"""
from __future__ import annotations

import argparse
import csv
import html as htmlmod
import json
import re
import subprocess
from collections import Counter
from pathlib import Path
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parents[3]
NAMES = {"ha20": "A20 haploinsufficiency", "axd": "Alexander disease", "lad1": "LAD-I",
         "ssadh": "SSADH deficiency", "danon": "Danon disease", "tangier": "Tangier disease"}


def words(s: str) -> set[str]:
    return {w for w in re.findall(r"[a-z]{4,}", s.lower())}


def file_text(p: Path) -> tuple[str, int | None]:
    if p.suffix == ".pdf":
        pages = None
        info = subprocess.run(["pdfinfo", str(p)], capture_output=True, text=True).stdout
        m = re.search(r"Pages:\s+(\d+)", info)
        if m:
            pages = int(m.group(1))
        txt = subprocess.run(["pdftotext", "-l", "3", str(p), "-"], capture_output=True, text=True).stdout
        return txt, pages
    raw = p.read_text(errors="ignore")
    raw = re.sub(r"<script.*?</script>|<style.*?</style>", " ", raw, flags=re.S)
    return htmlmod.unescape(re.sub(r"<[^>]+>", " ", raw)), None


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--date", required=True)
    a = ap.parse_args()
    meta = {r["pmid"] + r["disease"]: r for r in csv.DictReader(open(ROOT / f"reports/paywalled_papers_{a.date}.csv"))}
    res = [json.loads(l) for l in open(ROOT / f"data/literature/free_copies/results_{a.date}.jsonl") if l.strip()]
    rows = []
    for r in res:
        m = meta[r["pmid"] + r["disease"]]
        outcomes = [x.get("outcome", "") for x in r["attempts"]]
        hosts = [urlparse(x.get("final") or x["url"]).netloc for x in r["attempts"]]
        row = {
            "disease": r["disease"], "pmid": r["pmid"], "doi": r["doi"], "pmcid": r["pmcid"],
            "priority": r["priority"], "year": m["year"], "first_author": m["first_author"],
            "result": "", "file_kind": "", "pages": "", "title_word_match": "", "flags": "",
            "source_host": "", "attempts": ";".join(f"{h}:{o}" for h, o in zip(hosts, outcomes)),
            "manual_url": "",
        }
        if r["saved"]:
            p = ROOT / r["saved"]["file"]
            txt, pages = file_text(p)
            tw = words(m["title"])
            share = len(tw & words(txt)) / len(tw) if tw else 0.0
            flags = []
            if share < 0.6:
                flags.append("check_identity")
            if pages == 1:
                flags.append("one_page")
            if len(txt.strip()) < 500:
                flags.append("no_text_layer")
            row.update(result="saved", file_kind=r["saved"]["kind"], pages=pages or "",
                       title_word_match=f"{share:.2f}", flags=";".join(flags),
                       source_host=urlparse(r["saved"]["from"]).netloc)
        else:
            if "challenge" in outcomes:
                row["result"] = "blocked_by_challenge"
            elif any(o.startswith("http_") for o in outcomes):
                row["result"] = "http_error"
            elif outcomes:
                row["result"] = "no_pdf_found"
            else:
                row["result"] = "no_url"
            # Best link for a person: the PMC copy if there is one, else the first free URL tried.
            if r["pmcid"]:
                row["manual_url"] = f"https://pmc.ncbi.nlm.nih.gov/articles/{r['pmcid']}/"
            elif r["attempts"]:
                row["manual_url"] = r["attempts"][0]["url"]
            elif r["doi"]:
                row["manual_url"] = f"https://doi.org/{r['doi']}"
        rows.append(row)
    out = ROOT / f"analysis/corpus/free_copies/status_{a.date}.csv"
    with open(out, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)

    L = [f"# Free copies listed by Europe PMC: browser retrieval ({a.date})", "",
         "*Generated by `analysis/corpus/free_copies/summarize.py` from a headless-Chromium run "
         "(`fetch_browser.js`, Playwright defaults, no user-agent spoofing). Saved files are in the git-ignored "
         f"`data/literature/free_copies/<disease>/`; per-paper outcomes in `analysis/corpus/free_copies/status_{a.date}.csv`.*", "",
         "Input: the papers in `reports/paywalled_papers_<date>.csv` whose Europe PMC listing (2026-10-20) is OA or F. "
         "Challenge pages (Cloudflare, reCAPTCHA, Anubis) were recorded and not interacted with. "
         "These files are **not** in the frozen corpus; adding them is a decision for Jimmy.", "",
         "## Outcome by disease", "",
         "| Disease | Papers | Saved | of which flagged | Blocked by challenge | HTTP error | No PDF found | Has PMC copy |",
         "|---|---|---|---|---|---|---|---|"]
    tot = Counter()
    for d, name in NAMES.items():
        rs = [r for r in rows if r["disease"] == d]
        c = Counter(r["result"] for r in rs)
        c["n"] = len(rs)
        c["flag"] = sum(bool(r["flags"]) for r in rs if r["result"] == "saved")
        c["pmc"] = sum(bool(r["pmcid"]) for r in rs)
        tot.update(c)
        L.append(f"| {name} | {c['n']} | {c['saved']} | {c['flag']} | {c['blocked_by_challenge']} | {c['http_error']} | {c['no_pdf_found'] + c['no_url']} | {c['pmc']} |")
    L.append(f"| **Total** | **{tot['n']}** | **{tot['saved']}** | **{tot['flag']}** | **{tot['blocked_by_challenge']}** | **{tot['http_error']}** | **{tot['no_pdf_found'] + tot['no_url']}** | **{tot['pmc']}** |")
    hosts = Counter()
    for r in rows:
        if r["result"] == "blocked_by_challenge":
            for part in r["attempts"].split(";"):
                h, _, o = part.rpartition(":")
                if o == "challenge":
                    hosts[h] += 1
    L += ["", "## Hosts that showed a challenge page", "", "| Host | Links |", "|---|---|"]
    L += [f"| {h} | {n} |" for h, n in hosts.most_common(25)]
    flagged = [r for r in rows if r["result"] == "saved" and r["flags"]]
    if flagged:
        L += ["", "## Saved files to check by eye", "",
              "| Disease | PMID | Pages | Title-word match | Flags |", "|---|---|---|---|---|"]
        L += [f"| {NAMES[r['disease']]} | [{r['pmid']}](https://pubmed.ncbi.nlm.nih.gov/{r['pmid']}/) | {r['pages']} | {r['title_word_match']} | {r['flags']} |" for r in flagged]
    left = [r for r in rows if r["result"] != "saved"]
    left.sort(key=lambda r: (list(NAMES).index(r["disease"]), int(r["priority"]), r["pmid"]))
    L += ["", f"## Still to fetch by hand ({len(left)})", "",
          "Open these in an ordinary browser. Where the paper has a PMC copy the link goes to PMC "
          "(free to read; PMC shows automated browsers a reCAPTCHA, people usually get straight through).", "",
          "| Disease | P | Year | First author | PMID | Why not fetched | Link |", "|---|---|---|---|---|---|---|"]
    for r in left:
        L.append(f"| {NAMES[r['disease']]} | {r['priority']} | {r['year']} | {r['first_author']} | "
                 f"[{r['pmid']}](https://pubmed.ncbi.nlm.nih.gov/{r['pmid']}/) | {r['result']} | "
                 f"[{'PMC' if r['pmcid'] else 'free copy'}]({r['manual_url']}) |")
    (ROOT / f"reports/free_copies_{a.date}.md").write_text("\n".join(L) + "\n")
    print(dict(Counter(r["result"] for r in rows)), "flagged:", len(flagged))


if __name__ == "__main__":
    main()
