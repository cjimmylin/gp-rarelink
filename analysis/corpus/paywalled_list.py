"""List in-corpus papers whose full text we could not obtain, with links for manual retrieval.

For each of the six pilot diseases, reads data/literature/<d>/manifest.csv and
oa_elsewhere.csv and keeps rows with in_extraction_corpus == true and
access_status in {paywalled, not_found}:

  paywalled  no PMC/Europe PMC copy and no open publisher copy fetched
  not_found  no PMC copy and no DOI, so nothing could be looked up

Europe PMC's availability code (oa_elsewhere.csv, 2026-10-20) is carried over:
OA / F mean Europe PMC lists a free copy outside PMC that the fetch did not get
(often a host the network refused), S means subscription only, none means no
listing. Priority: 1 = relevant case report or case series/cohort, 2 = unclear
relevance or a review. Identifiers and bibliographic metadata only; no paper text.

  python3 analysis/corpus/paywalled_list.py --date 2026-11-14
"""

from __future__ import annotations

import argparse
import csv
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DISEASES = [
    ("ha20", "A20 haploinsufficiency", "TNFAIP3"),
    ("axd", "Alexander disease", "GFAP"),
    ("lad1", "Leukocyte adhesion deficiency I", "ITGB2"),
    ("ssadh", "SSADH deficiency", "ALDH5A1"),
    ("danon", "Danon disease", "LAMP2"),
    ("tangier", "Tangier disease", "ABCA1"),
]
MISSING = {"paywalled", "not_found"}
FREE_LABEL = {"OA": "open access copy listed", "F": "free copy listed", "S": "subscription", "none": "no listing", "": ""}


def priority(r: dict) -> int:
    return 1 if r["relevance"] == "yes" and r["study_type"] in ("case report", "case series/cohort") else 2


def collect() -> list[dict]:
    out = []
    for d, name, gene in DISEASES:
        base = ROOT / "data/literature" / d
        oa = {r["pmid"]: r for r in csv.DictReader(open(base / "oa_elsewhere.csv"))}
        for r in csv.DictReader(open(base / "manifest.csv")):
            if r["in_extraction_corpus"] != "true" or r["access_status"] not in MISSING:
                continue
            o = oa.get(r["pmid"], {})
            doi = r["doi"].strip()
            out.append({
                "disease": d,
                "disease_name": name,
                "gene": gene,
                "priority": priority(r),
                "pmid": r["pmid"],
                "doi": doi,
                "first_author": r["first_author"],
                "year": r["year"],
                "journal": r["journal"],
                "title": r["title"],
                "study_type": r["study_type"],
                "relevance": r["relevance"],
                "access_status": r["access_status"],
                "europepmc_availability": o.get("best", ""),
                "free_sites": o.get("free_sites", ""),
                "doi_url": f"https://doi.org/{doi}" if doi else "",
                "pubmed_url": f"https://pubmed.ncbi.nlm.nih.gov/{r['pmid']}/",
                "europepmc_url": f"https://europepmc.org/article/MED/{r['pmid']}",
                "retrieved": "",
                "retrieved_by": "",
                "notes": "",
            })
    order = {d: i for i, (d, _, _) in enumerate(DISEASES)}
    out.sort(key=lambda x: (order[x["disease"]], x["priority"], -int(x["year"] or 0), x["pmid"]))
    return out


def md_escape(s: str) -> str:
    return s.replace("|", "\\|").replace("\n", " ")


def write_md(rows: list[dict], path: Path, date: str) -> None:
    L = [
        f"# Corpus papers without full text, six pilot diseases ({date})",
        "",
        f"*Generated by `analysis/corpus/paywalled_list.py` from `data/literature/<disease>/manifest.csv` "
        f"and `oa_elsewhere.csv`. Spreadsheet version: `{path.with_suffix('.csv').name}` "
        "(has empty `retrieved`, `retrieved_by` and `notes` columns for tracking).*",
        "",
        "Rows are papers that passed title/abstract screening (`in_extraction_corpus = true`) but whose "
        "full text the pipeline could not obtain: **paywalled** (no PMC copy and no open publisher copy fetched) "
        "or **no DOI** (no PMC copy and no DOI to look up; use the PubMed link). They were never full-text screened, "
        "so some will turn out ineligible.",
        "",
        "- **Priority 1:** relevant (`yes`) case report or case series/cohort. **Priority 2:** relevance unclear, or a review.",
        "- **Free?** is Europe PMC's listing on 2026-10-20: **OA**/**F** = a free copy is listed somewhere "
        "(try the Europe PMC link first; our fetch was probably refused by the host), **S** = subscription only, "
        "**none** = no listing.",
        "- Open access only was used for the pilot (D-32). Papers obtained through institutional access need "
        "a decision on how they enter the corpus before extraction (they were not part of the frozen six-disease run).",
        "",
        "## Summary",
        "",
        "| Disease | Gene | Without full text | Priority 1 | Paywalled | No DOI | Free copy listed (OA/F) |",
        "|---|---|---|---|---|---|---|",
    ]
    tot = Counter()
    for d, name, gene in DISEASES:
        rs = [r for r in rows if r["disease"] == d]
        c = {
            "n": len(rs),
            "p1": sum(r["priority"] == 1 for r in rs),
            "pw": sum(r["access_status"] == "paywalled" for r in rs),
            "nf": sum(r["access_status"] == "not_found" for r in rs),
            "free": sum(r["europepmc_availability"] in ("OA", "F") for r in rs),
        }
        tot.update(c)
        L.append(f"| {name} | *{gene}* | {c['n']} | {c['p1']} | {c['pw']} | {c['nf']} | {c['free']} |")
    L.append(f"| **Total** | | **{tot['n']}** | **{tot['p1']}** | **{tot['pw']}** | **{tot['nf']}** | **{tot['free']}** |")
    for d, name, gene in DISEASES:
        rs = [r for r in rows if r["disease"] == d]
        L += ["", f"## {name} (*{gene}*), {len(rs)} papers", ""]
        L += ["| # | P | Year | First author | Title | Journal | Type | Free? | Links |", "|---|---|---|---|---|---|---|---|---|"]
        for i, r in enumerate(rs, 1):
            links = []
            if r["doi_url"]:
                links.append(f"[DOI]({r['doi_url']})")
            links.append(f"[PubMed]({r['pubmed_url']})")
            links.append(f"[EPMC]({r['europepmc_url']})")
            free = r["europepmc_availability"] or "–"
            if r["access_status"] == "not_found":
                free += " (no DOI)"
            L.append(
                f"| {i} | {r['priority']} | {r['year']} | {md_escape(r['first_author'])} | {md_escape(r['title'])} "
                f"| {md_escape(r['journal'])} | {r['study_type']} | {free} | {' · '.join(links)} |"
            )
    path.write_text("\n".join(L) + "\n")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--date", required=True)
    a = ap.parse_args()
    rows = collect()
    out = ROOT / "reports" / f"paywalled_papers_{a.date}.csv"
    with open(out, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    write_md(rows, out.with_suffix(".md"), a.date)
    print(f"{len(rows)} rows -> {out} and {out.with_suffix('.md')}")


if __name__ == "__main__":
    main()
