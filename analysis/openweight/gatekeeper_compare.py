"""Claude vs open-weight model, gatekeeper verdicts (pre-registration §7.5, D-10).

The same gatekeeper (v4, Claude Code helpers, the pv1 launch prompt) judged both runs: pv1-<d>
(Claude extraction) and ow-<d> (DeepSeek-V4.1-Flash extraction). This script reads each run's
gatekeeper_v4.csv (one row per claim, gatekeeper_merge.py) beside its claims.csv (same rows, same
order, with the span) and counts, over model claims (the ones a helper judged):

  verdicts                supported / partially_supported / unsupported / span_not_found
  by span                 the same split for claims with a quote and for claims with an empty
                          quote, since an empty quote can only rest on the paper's silence
  top fields              the fields with most unsupported claims

Rates carry exact (Clopper-Pearson) 95% intervals from gatekeeper_merge.share. These are the
gatekeeper's readings, not the human audit (which for D-10 waits on D-11).

  uv run python analysis/openweight/gatekeeper_compare.py --diseases ha20 ssadh
"""
import argparse
import csv
import json
from collections import Counter
from pathlib import Path

from pipeline.extract.claude_code.gatekeeper_merge import share

V = ("supported", "partially_supported", "unsupported", "span_not_found")


def one(d, run):
    base = Path(f"data/extracted/{d}/{run}")
    gk = list(csv.DictReader(open(base / "gatekeeper_v4.csv")))
    cl = list(csv.DictReader(open(base / "claims.csv")))
    assert len(gk) == len(cl), (run, len(gk), len(cl))
    tot, by_span, fields, papers, nf = Counter(), {"quote": Counter(), "empty": Counter()}, Counter(), Counter(), Counter()
    for g, c in zip(gk, cl):
        assert (g["pmid"], g["table"], g["row"], g["field"]) == (c["pmid"], c["table"], c["row"], c["field"]), (run, g["claim_id"])
        if g["source"] != "gatekeeper":
            continue
        v = g["verdict"]
        tot[v] += 1
        if c["found"] == "not_found":
            nf[v] += 1
        by_span["empty" if not (c["span"] or "").strip() else "quote"][v] += 1
        if v == "unsupported":
            fields[f"{g['table']}.{g['field']}"] += 1
            papers[g["pmid"]] += 1
    n = sum(tot.values())

    def rate(k, m):
        s = share(k, m)
        return {"k": k, "n": m, "share": s["share"], "ci95": s["ci95"]} if m else None

    return {"run": run, "model_claims": n, "verdicts": {k: tot[k] for k in V},
            "unsupported": rate(tot["unsupported"], n),
            "not_supported": rate(n - tot["supported"], n),
            "by_span": {k: {"claims": sum(c.values()), **{x: c[x] for x in V},
                            "unsupported": rate(c["unsupported"], sum(c.values()))} for k, c in by_span.items()},
            "quote_not_found_by_span_check": {"claims": sum(nf.values()), **{x: nf[x] for x in V}},
            "unsupported_top_fields": fields.most_common(8),
            "unsupported_top_papers": papers.most_common(5),
            "papers_with_unsupported": len(papers)}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--diseases", nargs="+", default=["ha20", "ssadh"])
    a = ap.parse_args()
    out = {d: {"claude": one(d, f"pv1-{d}"), "open": one(d, f"ow-{d}")} for d in a.diseases}
    Path("analysis/openweight/gatekeeper_compare.json").write_text(json.dumps(out, indent=1) + "\n")
    pc = lambda r: "—" if not r else f"{100 * r['share']:.2f}% ({100 * r['ci95'][0]:.2f}–{100 * r['ci95'][1]:.2f})"
    L = ["# Gatekeeper v4 on both runs (D-10)", "",
         "*Generated by `analysis/openweight/gatekeeper_compare.py`. Same gatekeeper, prompt and helpers on both runs; "
         "model claims only. Exact 95% intervals. The gatekeeper's reading, not the human audit.*", "",
         "| Measure | " + " | ".join(f"{d} Claude | {d} open-weight" for d in out) + " |", "|---|" + "---|---|" * len(out)]

    def row(name, f):
        L.append(f"| {name} | " + " | ".join(f"{f(out[d]['claude'])} | {f(out[d]['open'])}" for d in out) + " |")
    row("Model claims judged", lambda s: s["model_claims"])
    for v in V:
        row(v.replace("_", " ").capitalize(), lambda s, v=v: s["verdicts"][v])
    row("Unsupported rate", lambda s: pc(s["unsupported"]))
    row("Not supported (anything but supported)", lambda s: pc(s["not_supported"]))
    row("Claims with an empty quote", lambda s: s["by_span"]["empty"]["claims"])
    row("… of which unsupported", lambda s: s["by_span"]["empty"]["unsupported"]["k"] if s["by_span"]["empty"]["unsupported"] else 0)
    row("Unsupported rate, claims with a quote", lambda s: pc(s["by_span"]["quote"]["unsupported"]))
    row("Papers with an unsupported claim", lambda s: s["papers_with_unsupported"])
    L += ["", "Fields with most unsupported claims:", ""]
    for d in out:
        for k in ("claude", "open"):
            L.append(f"- {d} {'Claude' if k == 'claude' else 'open-weight'}: " +
                     "; ".join(f"{f} {n}" for f, n in out[d][k]["unsupported_top_fields"]))
    Path("analysis/openweight/gatekeeper_compare.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
