"""Collect the six-disease 10% repeat agreement (pre-registration: run-to-run stability; D-37).

Run analysis/poc/run_agreement.py for each disease first:
  for d in ha20 ssadh tangier lad1 axd danon; do
    uv run python analysis/poc/run_agreement.py --disease $d --run-a pv1-$d --run-b pv1-$d-repeat; done
Then:
  python3 -I analysis/six_disease/repeat_summary.py
writes analysis/six_disease/repeat_agreement_<date>.json and .md.

The pilot's guide (POC_DESIGN.md Stage 3) reads variant agreement below 0.9 as a
sign of unstable prompts. Variant agreement is reported on strings and on folded
cDNA/protein keys; features are compared on (individual label, text, status), so
wording differences lower them (see run_agreement.py).
"""

from __future__ import annotations

import json
from datetime import UTC, datetime
from pathlib import Path

DISEASES = ["ha20", "ssadh", "tangier", "lad1", "axd", "danon"]
KEYS = ["papers_compared", "individual_count_matches", "individual_label_jaccard", "variant_jaccard", "variant_key_jaccard",
        "checklist_agreement", "checklist_cells_compared", "feature_jaccard", "feature_jaccard_label_free", "hpo_status_jaccard_label_free"]


def main() -> int:
    rows = []
    for d in DISEASES:
        f = Path(f"analysis/poc/run_agreement_pv1-{d}_vs_pv1-{d}-repeat.json")
        sel = json.loads(Path(f"runs/pv1-{d}-repeat/selection.json").read_text())
        j = json.loads(f.read_text())
        rows.append({"disease": d, "selected": sel["n"], **{k: j.get(k) for k in KEYS},
                     "per_paper": j.get("per_paper"), "source": str(f)})
    today = datetime.now(UTC).date().isoformat()
    out = Path("analysis/six_disease")
    (out / f"repeat_agreement_{today}.json").write_text(json.dumps({"date": today, "seed": 20261020, "diseases": rows}, indent=1) + "\n")
    L = [f"# Six-disease 10% repeat: run-to-run agreement ({today})", "",
         "*Generated by `analysis/six_disease/repeat_summary.py` from `analysis/poc/run_agreement_pv1-<d>_vs_pv1-<d>-repeat.json`. "
         "Seeded draw (20261020) of ceil(10%) of each disease's papers with at least one individual row; same pinned files as the source run.*", "",
         "| Disease | Papers | Same individual count | Label Jaccard | Variant (strings) | Variant (keys) | Checklist agreement (cells) | Features (strict) | Features (label-free) |",
         "|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        L.append(f"| {r['disease']} | {r['papers_compared']} of {r['selected']} | {r['individual_count_matches']} | {r['individual_label_jaccard']} | "
                 f"{r['variant_jaccard']} | {r['variant_key_jaccard']} | {r['checklist_agreement']} ({r['checklist_cells_compared']}) | "
                 f"{r['feature_jaccard']} | {r['feature_jaccard_label_free']} |")
    (out / f"repeat_agreement_{today}.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
