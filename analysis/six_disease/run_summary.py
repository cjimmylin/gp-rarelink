"""Summarize the six-disease run (pipeline-v1.0, D-37) from each run's own outputs.

Reads, per disease, only files the run wrote:
  runs/pv1-<d>/manifest.json                         (papers, cost fields)
  data/extracted/<d>/pv1-<d>/per_paper/*.json         (individuals, variant rows)
  data/extracted/<d>/pv1-<d>/span_check.json          (verbatim-quote check)
  data/extracted/<d>/pv1-<d>/gatekeeper_v4_summary.json (verdicts, by paper, by field, about)

The gatekeeper's unsupported share is a second model read, not an error rate:
in the pilot it found 0.036% where the human audit found 4% (NOTES_FOR_AGENTS §3).
The pre-registered false-positive metric is the human 250-claim audit.

  python3 -I analysis/six_disease/run_summary.py
writes analysis/six_disease/run_summary_<date>.json and .md.
"""

from __future__ import annotations

import json
from collections import Counter
from datetime import UTC, datetime
from pathlib import Path

DISEASES = ["ha20", "ssadh", "tangier", "lad1", "axd", "danon"]
BAD = ("unsupported", "span_not_found")


def per_disease(d: str) -> dict:
    run = Path(f"data/extracted/{d}/pv1-{d}")
    man = json.loads(Path(f"runs/pv1-{d}/manifest.json").read_text())
    gs = json.loads((run / "gatekeeper_v4_summary.json").read_text())
    sc = json.loads((run / "span_check.json").read_text())
    papers = sorted(run.glob("per_paper/*.json"))
    ind = var = with_rows = 0
    for p in papers:
        t = json.loads(p.read_text()).get("tables") or {}
        ind += len(t.get("individuals") or [])
        var += len(t.get("variants") or [])
        with_rows += bool(t.get("individuals"))
    r = gs["rates_model_claims"]
    bad_by_paper = Counter({pm: sum(v.get(b, 0) for b in BAD) for pm, v in gs["by_paper"].items()})
    bad_total = sum(bad_by_paper.values())
    top3 = bad_by_paper.most_common(3)
    bad_by_field = Counter({f: sum(v.get(b, 0) for b in BAD) for f, v in gs["by_field"].items()})
    bad_about = Counter({a: sum(v.get(b, 0) for b in BAD) for a, v in gs["about_by_verdict"].items()})
    return {
        "disease": d, "run_id": f"pv1-{d}", "papers": len(papers), "papers_with_individual_rows": with_rows,
        "individual_rows": ind, "variant_rows": var,
        "span_check_problems": sc.get("n_problems"), "span_found_rate": sc.get("span_found_rate"),
        "claims_all": gs["claims"], "model_claims_judged": r["judged"],
        "verdicts": gs["verdicts"],
        "unsupported_or_not_found": r["unsupported_or_not_found"],
        "not_supported": r["not_supported"],
        "papers_with_any_unsupported": sum(1 for v in bad_by_paper.values() if v),
        "top3_papers_unsupported": top3,
        "top3_share_of_unsupported": round(sum(k for _, k in top3) / bad_total, 3) if bad_total else None,
        "unsupported_by_about": {a: k for a, k in bad_about.most_common() if k},
        "unsupported_top_fields": [(f, k) for f, k in bad_by_field.most_common(5) if k],
        "missing_chunks": gs["missing_chunks"], "model_claims_not_judged_yet": gs["model_claims_not_judged_yet"],
        "finished": man.get("finished"),
    }


def pct(x: float) -> str:
    return f"{100 * x:.2f}%"


def main() -> int:
    rows = [per_disease(d) for d in DISEASES]
    tot = {k: sum(r[k] for r in rows) for k in ("papers", "individual_rows", "variant_rows", "model_claims_judged")}
    tot["unsupported_or_not_found"] = sum(r["unsupported_or_not_found"]["k"] for r in rows)
    tot["not_supported"] = sum(r["not_supported"]["k"] for r in rows)
    today = datetime.now(UTC).date().isoformat()
    out = Path("analysis/six_disease")
    (out / f"run_summary_{today}.json").write_text(json.dumps({"date": today, "diseases": rows, "total": tot}, indent=1) + "\n")
    L = [f"# Six-disease run summary ({today})", "",
         "*Generated by `analysis/six_disease/run_summary.py` from each run's own outputs. "
         "Gatekeeper v4 shares are a second model read, not an error rate; the pre-registered false-positive metric is the human 250-claim audit.*", "",
         "| Disease | Papers | Individual rows | Variant rows | Span problems | Model claims judged | Unsupported (95% CI) | Not supported (95% CI) | Top 3 papers' share of unsupported |",
         "|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        u, n = r["unsupported_or_not_found"], r["not_supported"]
        L.append(f"| {r['disease']} | {r['papers']} | {r['individual_rows']} | {r['variant_rows']} | {r['span_check_problems']} | {r['model_claims_judged']:,} | "
                 f"{u['k']} ({pct(u['share'])}; {pct(u['ci95'][0])}–{pct(u['ci95'][1])}) | {n['k']} ({pct(n['share'])}; {pct(n['ci95'][0])}–{pct(n['ci95'][1])}) | "
                 f"{r['top3_share_of_unsupported']} ({', '.join(f'{p}: {k}' for p, k in r['top3_papers_unsupported'])}) |")
    L.append(f"| **all** | {tot['papers']} | {tot['individual_rows']} | {tot['variant_rows']} | | {tot['model_claims_judged']:,} | "
             f"{tot['unsupported_or_not_found']} ({pct(tot['unsupported_or_not_found'] / tot['model_claims_judged'])}) | "
             f"{tot['not_supported']} ({pct(tot['not_supported'] / tot['model_claims_judged'])}) | |")
    L += ["", "## Who the quote of each unsupported claim is about", "",
          "| Disease | " + " | ".join(["this_person", "named_group", "other_person", "cohort_general", "paper", "unclear"]) + " |",
          "|---|---|---|---|---|---|---|"]
    for r in rows:
        a = r["unsupported_by_about"]
        L.append(f"| {r['disease']} | " + " | ".join(str(a.get(k, 0)) for k in ["this_person", "named_group", "other_person", "cohort_general", "paper", "unclear"]) + " |")
    L += ["", "## Fields with the most unsupported claims", ""]
    for r in rows:
        L.append(f"- **{r['disease']}:** " + "; ".join(f"`{f}` {k}" for f, k in r["unsupported_top_fields"]))
    (out / f"run_summary_{today}.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
