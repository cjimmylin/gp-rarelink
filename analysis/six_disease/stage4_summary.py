"""Summarize Stage 4 (D-40) for the six pv1 runs from each run's own summary files.

Reads reconcile_summary.json, normalization_summary.json, binding_summary.json,
phenopacket_build.json and validation_report.json under data/extracted/<d>/pv1-<d>/.

  python3 -I analysis/six_disease/stage4_summary.py
writes analysis/six_disease/stage4_summary_<date>.json and .md.
"""

from __future__ import annotations

import json
from datetime import UTC, datetime
from pathlib import Path

DISEASES = ["ha20", "ssadh", "tangier", "lad1", "axd", "danon"]


def main() -> int:
    rows = []
    for d in DISEASES:
        run = Path(f"data/extracted/{d}/pv1-{d}")
        rc = json.loads((run / "reconcile_summary.json").read_text())
        nm = json.loads((run / "normalization_summary.json").read_text())
        bd = json.loads((run / "binding_summary.json").read_text())
        pb = json.loads((run / "phenopacket_build.json").read_text())
        vr = json.loads((run / "validation_report.json").read_text())
        rows.append({
            "disease": d,
            "individual_rows": rc["individuals_before_merging"], "identities": rc["identities_after_merging"],
            "merged_pairs": rc["merged_pairs"], "identities_with_target_variant": rc["identities_with_target_gene_variant"],
            "distinct_variant_descriptions": nm["distinct_descriptions"], "status_counts": nm["status_counts"],
            "cdna_normalized_share": nm["share_normalized_or_corrected_of_cdna"],
            "feature_rows": bd["feature_rows"], "feature_share_bound": bd["feature_share_bound"],
            "phenopackets": pb["counts"].get("phenopackets"), "with_interpretation": pb["counts"].get("with_interpretation"),
            "features_observed": pb["counts"].get("features_observed"), "features_excluded": pb["counts"].get("features_excluded"),
            "observed_excluded_conflicts": pb["observed_excluded_conflicts"],
            "schema_valid": vr["schema_valid"], "validation_errors": len(vr["errors"]) if isinstance(vr["errors"], list) else vr["errors"], "mane_select": nm["mane_select"],
        })
    today = datetime.now(UTC).date().isoformat()
    out = Path("analysis/six_disease")
    (out / f"stage4_summary_{today}.json").write_text(json.dumps({"date": today, "diseases": rows}, indent=1) + "\n")
    L = [f"# Stage 4 summary, six-disease run ({today})", "",
         "*Generated by `analysis/six_disease/stage4_summary.py` from each run's summary files (D-40 settings; gatekeeper-filtered build).*", "",
         "| Disease | Rows → identities (merges) | Identities with target-gene variant | cDNA descriptions normalized | Phenotype rows bound to HPO | Phenopackets (with interpretation) | Observed / excluded terms | Schema-valid, errors |",
         "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        L.append(f"| {r['disease']} | {r['individual_rows']} → {r['identities']} ({r['merged_pairs']}) | {r['identities_with_target_variant']} | "
                 f"{r['cdna_normalized_share']:.1%} | {r['feature_share_bound']:.1%} of {r['feature_rows']:,} | {r['phenopackets']} ({r['with_interpretation']}) | "
                 f"{r['features_observed']:,} / {r['features_excluded']:,} | {r['schema_valid']}, {r['validation_errors']} |")
    (out / f"stage4_summary_{today}.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
