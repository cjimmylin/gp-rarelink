"""Render a human review sheet for a pilot extraction run (Stage 2 gate).

Reads data/extracted/<disease>/<run_id>/per_paper/*.json and span_check.json
and writes reports/poc_review_<run_id>.md: per paper, the individuals,
variants, observed and excluded features with their quotes, and checklist
counts. Everything in the sheet comes from those files; nothing is computed by
hand.

  uv run python analysis/poc/smoke_review.py --disease ha20 --run-id poc-ha20-smoke-1
"""

from __future__ import annotations

import argparse
import json
from collections import Counter
from pathlib import Path


def v(cell):
    return (cell or {}).get("value")


def span(cell, n=160):
    s = (cell or {}).get("span")
    if isinstance(s, list):
        s = " || ".join(s)
    s = (s or "").replace("|", "¦").replace("\n", " ")
    return s if len(s) <= n else s[: n - 1] + "…"


def esc(x) -> str:
    return str(x).replace("|", "¦").replace("\n", " ")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--disease", required=True)
    ap.add_argument("--run-id", required=True)
    args = ap.parse_args(argv)
    run = Path("data/extracted") / args.disease / args.run_id
    check = json.loads((run / "span_check.json").read_text())
    out = [f"# Review sheet: {args.run_id}", "",
           f"Generated by `analysis/poc/smoke_review.py` from `{run}/`. Quotes are shortened to 160 characters here; the full quotes are in the per-paper JSON and `claims.csv`. In table quotes, `¦` stands for a table cell border.", "",
           "## Automated checks (`span_check.json`)", "",
           f"- Papers: {check['n_papers']}",
           f"- Asserted values: {check['counts'].get('values_asserted', 0)}; quotes found verbatim: exact {check['counts'].get('span_exact', 0)}, lenient {check['counts'].get('span_lenient', 0)}, not found {check['counts'].get('span_not_found', 0)}; values without a quote: {check['counts'].get('values_without_span', 0)}",
           f"- Structural problems: {check['n_problems']}", ""]
    for path in sorted((run / "per_paper").glob("*.json")):
        d = json.loads(path.read_text())
        t = d["tables"]
        pub = t["publications"][0]
        out += [f"## PMID {d['pmid']}: {esc(v(pub['first_author']))} {esc(v(pub['year']))} ({esc(v(pub['study_type']))})", "",
                f"*Relevance note:* {esc(d.get('relevance_note', ''))}", "",
                f"*Method note:* {esc(d.get('method_note', ''))}", "",
                "**Individuals**", "", "| Label | Proband | Sex | Onset (as written) | Disease label |", "|---|---|---|---|---|"]
        for r in t["individuals"]:
            out.append(f"| {esc(v(r['individual_label_in_paper']))} | {esc(v(r['is_proband']))} | {esc(v(r['sex']))} | {esc(v(r['age_at_onset_original_text']))} | {esc(v(r['disease_label_as_stated']))} |")
        out += ["", "**Variants**", "", "| Individual | Gene | Variant as printed | Zygosity | Inheritance |", "|---|---|---|---|---|"]
        for r in t["variants"]:
            out.append(f"| {esc(v(r['individual_label_in_paper']))} | {esc(v(r['gene_symbol_as_stated']))} | {esc(v(r['variant_original_string']))} | {esc(v(r['zygosity']))} | {esc(v(r['inheritance']))} |")
        exc = [r for r in t["phenotypic_features"] if v(r["status"]) == "excluded"]
        obs = [r for r in t["phenotypic_features"] if v(r["status"]) == "observed"]
        out += ["", f"**Features recorded as absent (excluded): {len(exc)}**: check that each quote really says absent for that person", "",
                "| Individual | Feature | Quote |", "|---|---|---|"]
        for r in exc:
            out.append(f"| {esc(v(r['individual_label_in_paper']))} | {esc(v(r['feature_text_as_stated']))} | {span(r['feature_text_as_stated'])} |")
        out += ["", f"**Features recorded as present (observed): {len(obs)}**", "", "| Individual | Feature | Quote |", "|---|---|---|"]
        for r in obs:
            out.append(f"| {esc(v(r['individual_label_in_paper']))} | {esc(v(r['feature_text_as_stated']))} | {span(r['feature_text_as_stated'])} |")
        cl = Counter(v(r["status"]) for r in t["phenotype_checklist"])
        out += ["", f"**Checklist (20 features × {len(t['individuals'])} individuals):** " + ", ".join(f"{k} {n}" for k, n in sorted(cl.items())), ""]
    dest = Path("reports") / f"poc_review_{args.run_id}.md"
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text("\n".join(out) + "\n")
    print(dest)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
