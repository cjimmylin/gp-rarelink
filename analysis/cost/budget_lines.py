"""Fill the Spent and Remaining columns of BUDGET.md's "Lines" table from this session's cost readings.

Input: analysis/cost/spend_segments.csv. Each row is one stretch between two readings of the
session's own cost figure (`get_session` -> usage.cost_usd, list price, helpers included). The
stretches must join end to start from $0 to the latest reading; the script stops if they don't.
Each stretch goes to one budget line, or is split between lines by the weights in `split`
("1:70,2:30" splits 70/30). "unassigned" collects setup, documents and gaps between runs (D-15
question 3 asks Jimmy where these belong).

These are estimates, not billing figures: the readings are list-price figures the session reports
about itself, they sometimes freeze or lag, and whether the session runs on the funded account is
D-15's open question. OpenRouter spend (D-10) is billed outside the award and is not counted.
Other sessions (e.g. "Rarelink POC study design") are not in these readings.

  python3 analysis/cost/budget_lines.py            # rewrite BUDGET.md
  python3 analysis/cost/budget_lines.py --check    # print only
"""
import argparse
import csv
import re
from collections import defaultdict
from pathlib import Path

SEG = Path("analysis/cost/spend_segments.csv")
BUDGET = Path("BUDGET.md")
START, END = "<!-- spend-by-line: start (generated by analysis/cost/budget_lines.py) -->", "<!-- spend-by-line: end -->"


def money(x):
    return f"${x:,.2f}"


def allocate():
    rows = list(csv.DictReader(SEG.open()))
    spent, prev = defaultdict(float), 0.0
    for r in rows:
        a, b = float(r["start_usd"]), float(r["end_usd"])
        if abs(a - prev) > 0.005:
            raise SystemExit(f"gap or overlap before '{r['work']}': previous end {prev}, this start {a}")
        amount, prev = b - a, b
        if ":" in r["line"]:
            parts = [p.split(":") for p in r["line"].split(",")]
            total = sum(float(w) for _, w in parts)
            for k, w in parts:
                spent[k] += amount * float(w) / total
        else:
            spent[r["line"]] += amount
    return spent, prev, rows[-1]["end_reading"]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    spent, total, when = allocate()
    text = BUDGET.read_text()
    out, core = [], 0.0
    for line in text.splitlines():
        m = re.match(r"^\| (\d) \| ([^|]+)\| \$([\d,]+) \| [^|]* \| [^|]* \|(.*)$", line)
        if m:
            n, req = m.group(1), float(m.group(3).replace(",", ""))
            s = spent.get(n, 0.0)
            if n in "123456":
                core += s
            line = f"| {n} | {m.group(2).strip()} | ${m.group(3)} | {money(s)} | {money(req - s)} |{m.group(4)}"
        elif line.startswith("| | **Core subtotal** |"):
            line = f"| | **Core subtotal** | **$30,000** | **{money(core)}** | **{money(30000 - core)}** | |"
        elif line.startswith("| | **Total requested** |"):
            line = f"| | **Total requested** | **$45,000** | **{money(total)}** | **{money(45000 - total)}** | Includes the unassigned amount below |"
        out.append(line)
    note = [START, "",
            f"**Spent is an estimate**, from this session's own cost readings ({money(total)} at {when}), split by line in "
            "`analysis/cost/spend_segments.csv`. It is not a billing figure: the readings are list-price figures that sometimes freeze or lag, "
            "and whether this session runs on the funded account is still open (D-15). Stretches that ran work for two lines are split by the "
            "weights stated in that file. The ledger below stays empty until billing figures from Settings > Usage arrive.",
            "",
            f"- **Unassigned: {money(spent.get('unassigned', 0.0))}.** Setup, documents, decisions and gaps between runs. D-15 question 3 asks where these belong; "
            "the total row counts them.",
            "- **Not counted:** OpenRouter spend for the open-weight model (D-10; billed outside the award, see the D-10 rows below), and other sessions such "
            "as \"Rarelink POC study design\", whose usage is not in these readings.",
            "", END]
    body = "\n".join(out)
    if START in body:
        body = re.sub(re.escape(START) + r".*?" + re.escape(END), "\n".join(note), body, flags=re.S)
    else:
        anchor = "**Three notes:**"
        body = body.replace(anchor, "\n".join(note) + "\n\n" + anchor, 1)
    body = body.replace('"Spent" and "Remaining" will be filled from the ledger below by script once entries exist. Totals are never added up by hand.',
                        '"Spent" and "Remaining" are filled by `analysis/cost/budget_lines.py`. Totals are never added up by hand.')
    for k in sorted(spent):
        print(f"line {k}: {money(spent[k])}")
    print(f"total {money(total)} at {when}")
    if not a.check:
        BUDGET.write_text(body + ("\n" if text.endswith("\n") else ""))


if __name__ == "__main__":
    main()
