"""Findings report for the Majeed syndrome run (pv1s-majeed): reports/majeed_pv1s_findings.md.

Every number is read from committed files: the run's summary JSONs (pushed under D-51),
analysis/majeed/o2, analysis/majeed/o3, analysis/majeed/helper_costs.json,
analysis/majeed/d51_public_files.json, data/literature/majeed/search_summary.json and the
ClinVar counts of the 2026-11-15 snapshot.

  python3 analysis/majeed/report.py
"""
from __future__ import annotations

import csv
import json
from pathlib import Path

R = Path("data/extracted/majeed/pv1s-majeed")
J = lambda p: json.loads(Path(p).read_text())  # noqa: E731


def ci(x: dict) -> str:
    return f"{100 * x['share']:.1f}% ({x['k']}/{x['n']}; 95% CI {100 * x['ci95'][0]:.1f}–{100 * x['ci95'][1]:.1f})"


def main() -> int:
    rec, norm, bind = J(R / "reconcile_summary.json"), J(R / "normalization_summary.json"), J(R / "binding_summary.json")
    gk, build, val = J(R / "gatekeeper_v4_summary.json"), J(R / "phenopacket_build.json"), J(R / "validation_report.json")
    sc = J(R / "span_check.json")
    o2 = J("analysis/majeed/o2/o2_majeed.json")
    o3 = J("analysis/majeed/o3/summary.json")
    cand = list(csv.DictReader(open("analysis/majeed/o3/candidates.csv")))
    recl = list(csv.DictReader(open("analysis/majeed/o3/reclassification_candidates.csv")))
    cost = J("analysis/majeed/helper_costs.json")
    d51 = J("analysis/majeed/d51_public_files.json")
    srch = J("data/literature/majeed/search_summary.json")["summary"]
    cv = J("analysis/poc/reference_snapshot/2026-11-15/counts_LPIN2.json")
    a, mc = o2["all_papers"], gk["rates_model_claims"]
    v = gk["verdicts"]
    stages = {s["stage"]: s for s in cost["stages"]}
    run_usd = sum(stages[k]["usd_estimate"] for k in ("checklist", "hpo_map", "extract", "gatekeeper", "hpo_binding", "runbook_explore") if k in stages)
    scr_usd = sum(stages[k]["usd_estimate"] for k in ("screen_ta", "screen_fulltext") if k in stages)
    bc = cv["single_gene_records"]["by_classification"]
    plp = sum(bc.get(k, 0) for k in ("P", "LP", "P/LP"))
    pb = build["counts"]
    L = [
        "# Majeed syndrome (LPIN2): search to phenopackets with the frozen pipeline (`pv1s-majeed`, 2026-11-15)",
        "",
        "*Generated by `analysis/majeed/report.py`. Exploratory: Majeed syndrome is a substitute disease (pre-registration §4.2), not part of the six-disease study; "
        "these results are reported on their own and never pooled with the registered runs. Decision log: `DECISIONS.md`, 2026-11-15. All gap candidates are *pending adjudication*.*",
        "",
        "## Corpus",
        "",
        f"- {srch['manifest_rows']} PubMed records from every search method (log: `data/literature/majeed/search.md`); {srch['in_corpus']} passed title/abstract screening; "
        f"{srch['fulltext']} had open full text, including copies found by hand; {srch['eligible_all']} eligible after full-text screening ({srch['eligible_primary']} primary reports).",
        f"- Run on {sc['n_papers']} documents: the eligible PubMed papers plus two eligible records with no PMID (N66, a PReS 2011 abstract; N88, Han 2025). N76 left out as the preprint of Liu 2019 (PMID 31727123).",
        f"- Checklist: 20 features from three openly licensed reviews (Ferguson 2021, Wang 2025, Haşlak 2025; `configs/checklists/majeed.json`); one item, warmth or redness over bone or joint, has no HPO term of its scope and is marked unmapped.",
        "",
        "## Extraction and gatekeeper",
        "",
        f"- Span check: {100 * sc['span_found_rate']:.1f}% of spans found verbatim, {sc['n_problems']} problems after one repair-only resume (empty label spans in one paper).",
        f"- People: {rec['individuals_before_merging']} rows, {rec['identities_after_merging']} identities after {rec['merged_pairs']} merges; {rec['identities_with_target_gene_variant']} with an LPIN2 variant row.",
        f"- Gatekeeper v4 on {mc['judged']} model claims: supported {v['supported']}, partially supported {v['partially_supported']}, unsupported {v['unsupported']}. "
        f"Unsupported or not found {ci(mc['unsupported_or_not_found'])}; not fully supported {ci(mc['not_supported'])}. These are gatekeeper rates, not audited error rates (no human audit).",
        "- Four gatekeeper chunks (Ferguson 2021 ×3, Sharma 2013) were judged again by fresh helpers because the first helpers assigned verdicts with a script (one was refused by the permission check); "
        "the first files are kept under `gatekeeper_v4_set_aside/` (local). The re-judgement changed verdicts: e.g. 14 'spine involvement excluded' claims became partially supported because whole-body MRI was not done in most patients.",
        "",
        "## Stage 4 and phenopackets",
        "",
        f"- Variants: {norm['distinct_descriptions']} distinct descriptions; {100 * norm['share_normalized_or_corrected']:.1f}% normalized or corrected by VariantValidator "
        f"({100 * norm['share_normalized_or_corrected_of_cdna']:.1f}% of cDNA descriptions) on MANE Select {norm['mane_select']}. Older papers use NM_014646.2, whose CDS has the same length (2,691 nt).",
        f"- HPO: {100 * bind['feature_share_bound']:.1f}% of feature rows bound after the model pass (one Sonnet batch of 217 phrases).",
        f"- Phenopackets: {pb['phenopackets']}, all schema-valid ({val['counts']['schema_valid'] if 'counts' in val else 'see validation_report.json'}); {pb['with_interpretation']} with an interpretation; "
        f"{pb['variants_with_normalized_expression']} variants with a normalized expression and {pb['variants_original_string_only']} with the original string only; "
        f"{build['observed_excluded_conflicts']} observed/excluded conflicts listed in `phenopacket_build.json`.",
        "",
        f"## ClinVar concordance (O2; snapshot 2026-11-15, release of {o2['clinvar_variant_summary_last_modified']})",
        "",
        f"- LPIN2 in ClinVar: {cv['single_gene_records']['total']} single-gene records, {plp} P/LP, {bc.get('VUS', 0)} VUS.",
        f"- Gene correct: {ci(o2['gene_7_2_1'])}." if isinstance(o2.get('gene_7_2_1'), dict) and 'share' in o2['gene_7_2_1'] else "- Gene: see `o2_majeed.json`.",
        f"- Overlap (extracted distinct alleles found in ClinVar, tier 1): {ci(a['overlap_tier1'])}.",
        f"- HGVS recall against the ClinVar variant–citation pairs of corpus papers: tier 1 {ci(a['hgvs_recall_tier1'])}; tiers 1+2 {ci(a['hgvs_recall_tier12'])}. "
        "Low mainly because ClinVar cites some corpus papers (e.g. Ferguson 2005) for variants those papers do not report (`o2_recall_misses.csv`).",
        f"- Classification agreement where the authors state one: {ci(a['classification_agreement_among_stated'])}. Condition names the disease: {ci(a['condition_names_disease'])}.",
        "- OMIM not checked (the frozen OMIM pages cover only the six diseases).",
        "",
        "## Gap candidates (O3 stage 1)",
        "",
        f"- {o3['totals']['gap_candidates']} gatekeeper-supported alleles absent from ClinVar, {o3['totals']['reclassification_candidates']} reclassification candidate(s). All pending adjudication by the RGI panel; none is to be submitted without sign-off.",
        "",
        "| Candidate | HGVS (MANE) | Predicted protein | Protein check | Papers | Authors' class |",
        "|---|---|---|---|---|---|",
    ]
    for c in cand:
        L.append(f"| {c['candidate_id']} | {c['hgvs_c'].split(':', 1)[1]} | {c['hgvs_p_predicted'].split(':', 1)[1]} | {c['protein_check']} | {c['pmids']} | {c['author_class']} |")
    for r in recl:
        L += ["", f"Reclassification candidate: {r['hgvs_c']} ({r['hgvs_p_predicted']}), ClinVar {r['clinvar_variation_id']} '{r['clinvar_class']}' ({r['clinvar_review_status']}); papers {r['pmids']}."]
    L += [
        "",
        "## Licences and what is public (D-51)",
        "",
        f"- {len(d51['open_documents'])} documents are openly licensed; {len(d51['held_back_documents'])} are not ({', '.join(d51['held_back_documents'])}). "
        f"Their extraction outputs, and the {d51['phenopackets_held_back']} phenopackets that quote them, are kept out of the repository; "
        f"{d51['phenopackets_public']} phenopackets and the open documents' per-paper and gatekeeper files are committed (`analysis/majeed/d51_public_files.json`).",
        "",
        "## Spend (helper tokens; estimates, not billing figures)",
        "",
        f"- Pipeline run: about ${run_usd:.0f} (extraction ${stages['extract']['usd_estimate']:.0f}, gatekeeper ${stages['gatekeeper']['usd_estimate']:.0f} including re-judgements, "
        f"checklist and map ${stages['checklist']['usd_estimate'] + stages['hpo_map']['usd_estimate']:.0f}, HPO binding ${stages['hpo_binding']['usd_estimate']:.0f}, runbook ${stages['runbook_explore']['usd_estimate']:.0f}); ceiling was $120. "
        f"Search screening: about ${scr_usd:.0f}. Source: `analysis/majeed/helper_costs.json`.",
        "",
        "## Limits",
        "",
        "- No human audit of extraction or screening yet; gatekeeper agreement is not accuracy.",
        f"- {srch['fulltext_screen'].get('not_accessible', 0)} corpus papers have no open copy, including the founding reports (Majeed 1989 and 2001, Al-Mosawi 2007) and several cohorts; the Chavan 2021 literature table (Supplementary Table 3) was not available.",
        "- Several patients appear in more than one paper (reviews re-tabulating case reports); deduplication merged only what the merge policy could support, so identity counts are upper bounds.",
    ]
    out = Path("reports/majeed_pv1s_findings.md")
    out.write_text("\n".join(L) + "\n")
    print(out.read_text())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
